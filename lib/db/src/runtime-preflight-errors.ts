// Closed diagnostic vocabulary. Never return raw messages, SQL, URLs or details.
const SAFE_CODES = [
  "RUNTIME_PREFLIGHT_FLAG_INVALID",
  "RUNTIME_PREFLIGHT_PRODUCTION_REQUIRED",
  "RUNTIME_PREFLIGHT_REQUIRES_REPLIT_BACKEND",
  "RUNTIME_PREFLIGHT_FAILED",
  "RUNTIME_PREFLIGHT_CLOSE_FAILED",
  "RUNTIME_SECRET_MISSING",
  "RUNTIME_CONNECTION_INVALID",
  "RUNTIME_DESTINATION_OR_ROLE_INVALID",
  "RUNTIME_CA_NOT_APPROVED",
  "GLOBAL_TLS_DISABLE_NOT_ALLOWED",
  "RUNTIME_TLS_NOT_VERIFIED",
  "RUNTIME_TLS_HOSTNAME_NOT_VERIFIED",
  "RUNTIME_PREFLIGHT_NOT_READONLY",
  "RUNTIME_ROLE_NOT_APPROVED",
  "RUNTIME_AUTHENTICATION_FAILED",
  "RUNTIME_AUTHORIZATION_FAILED",
  "RUNTIME_TLS_CERTIFICATE_REJECTED",
  "RUNTIME_NETWORK_FAILED",
  "RUNTIME_CONNECTION_TIMEOUT",
  "RUNTIME_SESSION_STARTUP_REJECTED",
  "RUNTIME_DATABASE_UNAVAILABLE",
  "RUNTIME_METADATA_PERMISSION_DENIED",
  "RUNTIME_METADATA_QUERY_TIMEOUT",
] as const;
type RuntimePreflightCode = typeof SAFE_CODES[number];
const approvedMessages = new Set<string>(SAFE_CODES);
const driverCodes: Readonly<Record<string, RuntimePreflightCode>> = Object.freeze({
  "28P01": "RUNTIME_AUTHENTICATION_FAILED",
  "28000": "RUNTIME_AUTHORIZATION_FAILED",
  "42501": "RUNTIME_METADATA_PERMISSION_DENIED",
  "08P01": "RUNTIME_SESSION_STARTUP_REJECTED",
  "57P03": "RUNTIME_DATABASE_UNAVAILABLE",
  "57014": "RUNTIME_METADATA_QUERY_TIMEOUT",
  ENOTFOUND: "RUNTIME_NETWORK_FAILED",
  EAI_AGAIN: "RUNTIME_NETWORK_FAILED",
  ECONNREFUSED: "RUNTIME_NETWORK_FAILED",
  ECONNRESET: "RUNTIME_NETWORK_FAILED",
  ENETUNREACH: "RUNTIME_NETWORK_FAILED",
  ETIMEDOUT: "RUNTIME_CONNECTION_TIMEOUT",
  SELF_SIGNED_CERT_IN_CHAIN: "RUNTIME_TLS_CERTIFICATE_REJECTED",
  UNABLE_TO_VERIFY_LEAF_SIGNATURE: "RUNTIME_TLS_CERTIFICATE_REJECTED",
  UNABLE_TO_GET_ISSUER_CERT_LOCALLY: "RUNTIME_TLS_CERTIFICATE_REJECTED",
  DEPTH_ZERO_SELF_SIGNED_CERT: "RUNTIME_TLS_CERTIFICATE_REJECTED",
  CERT_HAS_EXPIRED: "RUNTIME_TLS_CERTIFICATE_REJECTED",
  ERR_TLS_CERT_ALTNAME_INVALID: "RUNTIME_TLS_HOSTNAME_NOT_VERIFIED",
});

export class RuntimePreflightError extends Error {
  constructor(public readonly code: RuntimePreflightCode) {
    super(code);
    this.name = "RuntimePreflightError";
  }
}

export function runtimePreflightErrorCode(error: unknown): RuntimePreflightCode {
  if (error instanceof Error && approvedMessages.has(error.message)) {
    return error.message as RuntimePreflightCode;
  }
  const code = error && typeof error === "object" && "code" in error ? error.code : undefined;
  return typeof code === "string" && Object.hasOwn(driverCodes, code)
    ? driverCodes[code] : "RUNTIME_PREFLIGHT_FAILED";
}
