import test, { after } from "node:test";
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, statSync, existsSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { encryptDump } from "./pipeline.mjs";

const socket = process.env.NITROCROP_SYNTHETIC_SOCKET;
assert.match(socket ?? "", /^\/tmp\/nitrocrop-backup-preflight\.[a-zA-Z0-9]+$/);
assert.equal(process.env.DATABASE_URL, undefined);
assert.equal(process.env.REPLIT_PROD_BACKUP_URL, undefined);
assert.equal(process.env.SUPABASE_QA_ADMIN_URL, undefined);
const dir = mkdtempSync(join(tmpdir(), "nitrocrop-cipher-test."));
const noPassword = join(dir, "empty.pgpass");
const noService = join(dir, "empty.pg_service.conf");
writeFileSync(noPassword, "", { mode: 0o600 });
writeFileSync(noService, "", { mode: 0o600 });
const localEnv = { PATH: process.env.PATH, PGPASSFILE: noPassword, PGSERVICEFILE: noService };
const env = { ...localEnv, PGOPTIONS: "-c default_transaction_read_only=on" };
const conn = (db) => `host=${socket} port=55440 user=backup_synthetic dbname=${db}`;
function sql(db, query) {
  return execFileSync("psql", ["-X", "--no-password", "-v", "ON_ERROR_STOP=1", "-At",
    "--dbname", conn(db), "-c", query], { env: localEnv, encoding: "utf8" }).trim();
}
sql("postgres", "CREATE DATABASE synthetic_backup");
sql("synthetic_backup", `
  CREATE TABLE app_users(id text PRIMARY KEY, clerk_user_id text UNIQUE, role text);
  CREATE TABLE osservazioni(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id text REFERENCES app_users(id), ndvi numeric, latitude numeric,
    longitude numeric, note text, sample bytea);
  CREATE TABLE privacy_requests(id text PRIMARY KEY, user_id text REFERENCES app_users(id));
  CREATE TABLE security_events(id text PRIMARY KEY, actor_id text, target_id text);
  CREATE TABLE security_state(key text PRIMARY KEY, value text);
  INSERT INTO app_users VALUES ('synthetic-user','synthetic-clerk','user');
  INSERT INTO osservazioni(owner_id,ndvi,latitude,longitude,note,sample)
    VALUES ('synthetic-user',0.61,42.00,12.00,'SYNTHETIC — prova ñ',decode('0000ff','hex')),
           ('synthetic-user',0.42,NULL,NULL,NULL,NULL);
  INSERT INTO privacy_requests VALUES ('synthetic-request','synthetic-user');
  INSERT INTO security_events VALUES ('synthetic-event',NULL,NULL);
  INSERT INTO security_state VALUES ('synthetic-marker','not-real');
`);
const baseline = sql("synthetic_backup",
  "SELECT json_agg(t ORDER BY id)::text FROM osservazioni t");
const key = join(dir, "synthetic-key.txt");
execFileSync("age-keygen", ["--output", key], { env: localEnv, stdio: ["ignore", "ignore", "pipe"] });
const recipient = execFileSync("age-keygen", ["-y", key], { env: localEnv, encoding: "utf8" }).trim();
const dumpArgs = ["--dbname", conn("synthetic_backup"), "--format=custom", "--compress=3",
  "--quote-all-identifiers", "--lock-wait-timeout=1000", "--no-password"];
const outputPath = join(dir, "database.dump.age");
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");
let result;

test("real pg_dump -> age pipeline verifies the whole synthetic archive without a plaintext file", async () => {
  result = await encryptDump({ dumpArgs, env, recipient, outputPath });
  assert.ok(result.rawBytes > 0);
  assert.equal(statSync(outputPath).mode & 0o777, 0o600);
  assert.equal(sha(readFileSync(outputPath)), result.encryptedSha256);
  assert.ok(readFileSync(outputPath).toString("utf8", 0, 24).startsWith("age-encryption.org/v1\n->"));
  assert.equal(sql("synthetic_backup",
    "SELECT json_agg(t ORDER BY id)::text FROM osservazioni t"), baseline);
});
test("decrypts with the disposable synthetic private key and lists all five tables", () => {
  const raw = execFileSync("age", ["--decrypt", "--identity", key, outputPath], { env: localEnv });
  assert.equal(sha(raw), result.rawSha256);
  const toc = execFileSync("pg_restore", ["--list"], { env: localEnv, input: raw, encoding: "utf8" });
  for (const table of ["app_users", "osservazioni", "privacy_requests", "security_events", "security_state"]) {
    assert.match(toc, new RegExp(`TABLE DATA public ${table} `));
  }
  sql("postgres", "CREATE DATABASE synthetic_restored");
  execFileSync("pg_restore", ["--dbname", conn("synthetic_restored"),
    "--single-transaction", "--exit-on-error"], { env: localEnv, input: raw });
  assert.equal(sql("synthetic_restored",
    "SELECT json_agg(t ORDER BY id)::text FROM osservazioni t"), baseline);
  assert.equal(sql("synthetic_restored", "SELECT last_value FROM osservazioni_id_seq"), "2");
  assert.equal(sql("synthetic_restored", "SELECT count(*) FROM privacy_requests"), "1");
});
test("wrong synthetic key cannot decrypt", () => {
  const otherKey = join(dir, "wrong-synthetic-key.txt");
  execFileSync("age-keygen", ["-o", otherKey], { env: localEnv, stdio: ["ignore", "ignore", "pipe"] });
  assert.notEqual(spawnSync("age", ["-d", "-i", otherKey, outputPath], { env: localEnv }).status, 0);
});
test("tampering ciphertext fails authentication", () => {
  const bytes = readFileSync(outputPath);
  bytes[bytes.length - 1] ^= 1;
  const damaged = join(dir, "damaged.age");
  writeFileSync(damaged, bytes, { mode: 0o600 });
  assert.notEqual(spawnSync("age", ["-d", "-i", key, damaged], { env: localEnv }).status, 0);
});
for (const [name, patch] of [
  ["dump error", { dumpArgs: ["--invalid-synthetic-option"] }],
  ["encryption error", { programs: { age: "false" } }],
  ["parser error", { programs: { restore: "false" } }],
  ["missing executable", { programs: { dump: "/synthetic-nonexistent-program" } }],
  ["byte limit", { maxBytes: 1 }],
]) {
  test(`${name}: aborts pipeline, redacts errors and leaves no partial archive`, async () => {
    const path = join(dir, `${name.replaceAll(" ", "-")}.age`);
    await assert.rejects(encryptDump({
      dumpArgs, env, recipient, outputPath: path, ...patch,
    }), { message: "BACKUP_PIPELINE_FAILED_NO_VALID_ARCHIVE" });
    assert.equal(existsSync(path), false);
  });
}
test("timeout stops subprocesses and removes incomplete ciphertext", async () => {
  const sleeper = join(dir, "synthetic-sleeper");
  writeFileSync(sleeper, "#!/bin/sh\nexec sleep 20\n", { mode: 0o700 });
  const path = join(dir, "timeout.age");
  await assert.rejects(encryptDump({ dumpArgs: [], env, recipient,
    outputPath: path, timeoutMs: 150, programs: { dump: sleeper } }));
  assert.equal(existsSync(path), false);
});
test("an existing backup is not overwritten or deleted", async () => {
  const before = sha(readFileSync(outputPath));
  await assert.rejects(encryptDump({ dumpArgs, env, recipient, outputPath }));
  assert.equal(sha(readFileSync(outputPath)), before);
});
test("forbids implicit application environment", async () => {
  await assert.rejects(encryptDump({ dumpArgs, recipient, outputPath: join(dir, "unsafe.age"),
    env: { ...env, DATABASE_URL: "synthetic-not-a-real-url" } }), /UNEXPECTED_ENVIRONMENT/);
});
test("public recipient is mandatory", async () => {
  await assert.rejects(encryptDump({ dumpArgs, env, outputPath: join(dir, "no-key.age") }),
    /INVALID_PUBLIC_RECIPIENT/);
});
test("default libpq credential and service files are never implicitly used", async () => {
  await assert.rejects(encryptDump({ dumpArgs, recipient, outputPath: join(dir, "implicit-libpq.age"),
    env: { PATH: process.env.PATH } }), /EXPLICIT_LIBPQ_FILES_REQUIRED/);
});
test("private output directory is mandatory", async () => {
  const loose = join(dir, "loose");
  mkdirSync(loose, { mode: 0o755 });
  await assert.rejects(encryptDump({ dumpArgs, env, recipient, outputPath: join(loose, "bad.age") }),
    /PRIVATE_OUTPUT_DIRECTORY_REQUIRED/);
});
after(() => rmSync(dir, { recursive: true, force: true }));
